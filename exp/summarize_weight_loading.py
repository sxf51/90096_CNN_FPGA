#!/usr/bin/env python3
"""Generate the WS0-WS4 measurement table without mixing HLS, RTL and route data."""
import csv
import json
from analyze_arch import write_csv
from run_exp import ROOT, markdown_table, number
from route_gates import archive_route_evidence


def main():
    state = json.loads((ROOT / "experiments/weight_loading_state.json").read_text())
    requested = set(state.get("experiment_ids", ["F25", "W17", "F26", "F27", "F89"]))
    loader_path = ROOT / "experiments/weight_loading_comparison.csv"
    loaders = {row["id"]: row for row in csv.DictReader(loader_path.open(newline=""))} if loader_path.is_file() else {}
    rows = []
    for path in sorted((ROOT / "experiments").glob("*_*/metrics.json")):
        metrics = json.loads(path.read_text())
        exp_id = metrics["id"]
        if exp_id not in requested:
            continue
        config = json.loads(path.with_name("config.json").read_text())
        observed = config.get("verification", {})
        route = archive_route_evidence(path.parent) if config.get("operation") == "impl" else {}
        routed_period = number(observed.get("impl_target_clock_ns"))
        if routed_period is None and config.get("operation") == "impl":
            routed_period = number(config.get("implementation_clock_ns", config.get("clock")))
        wns = number(observed.get("impl_WNS_ns"))
        parent = config.get("verify_parent")
        row = {"id": exp_id, "parent": parent, "operation": config.get("operation", "csim/csynth"),
               **{key: metrics.get(key) for key in ("T_target", "clock_target_ns", "clock_est_ns",
                  "latency_cycles", "interval_cycles", "latency_ms_est", "DSP", "BRAM18K", "URAM", "LUT", "FF",
                  "bit_exact", "border_mse", "delta_psnr", "status", "md_path")},
               "outside_LUT": number(loaders.get(exp_id, {}).get("outside_LUT")),
               "ws2_all_gates": loaders.get(exp_id, {}).get("ws2_all_gates"),
               "rtl_latency_cycles": number(observed.get("rtl_latency_max")),
               "rtl_interval_cycles": number(observed.get("rtl_interval_max")),
               "route_target_ns": routed_period if wns is not None else None,
               "route_WNS_ns": wns, "route_TNS_ns": number(observed.get("impl_TNS_ns")),
               "route_period_from_slack_ns": routed_period-wns if wns is not None and routed_period is not None else None,
               **{"route_"+key: number(observed.get("impl_"+key)) for key in ("DSP", "LUT", "FF", "URAM")},
               "route_BRAM18K": 2*number(observed["impl_BRAM36"]) if number(observed.get("impl_BRAM36")) is not None else None,
               "timing_met": observed.get("timing_met"),
               "route_feasible": route.get("route_feasible"),
               "rtl_source": None, "rtl_frame_ms_at_route_target": None}
        rows.append(row)
    for row in rows:
        if row["operation"] != "impl" or row["route_target_ns"] is None:
            continue
        matches = []
        for path in sorted((ROOT / "experiments").glob("*_*/config.json")):
            config = json.loads(path.read_text())
            rtl = number(config.get("verification", {}).get("rtl_latency_max"))
            if config.get("operation") == "cosim" and config.get("verify_parent") == row["parent"] and rtl is not None:
                interval = number(config.get("verification", {}).get("rtl_interval_max"))
                matches.append((config["id"], rtl, interval))
        if len(matches) == 1:
            row["rtl_source"], row["rtl_latency_cycles"], row["rtl_interval_cycles"] = matches[0]
            if row["route_feasible"] is True:
                row["rtl_frame_ms_at_route_target"] = matches[0][1]*row["route_target_ns"]/1e6
    if not rows:
        raise RuntimeError("No completed workstream measurements")
    write_csv(ROOT / "experiments/weight_loading_workstream.csv", rows, list(rows[0]))
    linked = [{**row, "id": "["+row["id"]+"]("+row["md_path"]+")"} for row in rows]
    hls_columns = ["id", "parent", "T_target", "clock_target_ns", "clock_est_ns", "latency_cycles",
                   "interval_cycles", "latency_ms_est", "DSP", "BRAM18K", "LUT", "outside_LUT", "FF",
                   "bit_exact", "border_mse", "delta_psnr", "ws2_all_gates", "status"]
    physical_columns = ["id", "parent", "rtl_source", "rtl_latency_cycles", "rtl_interval_cycles",
                        "route_target_ns", "route_WNS_ns", "route_TNS_ns", "route_period_from_slack_ns",
                        "route_DSP", "route_BRAM18K", "route_LUT", "route_FF", "timing_met", "route_feasible",
                        "rtl_frame_ms_at_route_target", "status"]
    block = "<!-- AUTO: WORKSTREAM START -->\n\n"
    block += "## Measured WS0-WS4 results\n\nGenerated by `python3 exp/summarize_weight_loading.py`; numeric values are parsed from archived reports.\n\n"
    block += "HLS estimates (verification rows inherit their parent and are not new synthesis measurements):\n\n"
    block += markdown_table(linked, hls_columns)
    block += "\nRTL and routed results, kept separate:\n\n"
    block += markdown_table([row for row in linked if row["operation"] in {"cosim", "impl"}], physical_columns)
    block += "\nTimes derived from RTL cycles at a routed target are conditional on `timing_met=true`. Target minus negative WNS is a slack-derived period estimate, not a proven closed clock. Missing values remain unknown. No board validation has run.\n\n"
    block += "Routed/HLS resource calibration from [route_calibration.csv](route_calibration.csv). Historical HLS status is retained; docs/0005 now defines final feasibility using routed resources/timing.\n\n"
    block += "![Routed resource calibration](figs/route_calibration.png)\n\n"
    block += "Host utilization from archived CPU/memory CSV files (short snapshots are labeled; old runs without CPU telemetry stay unknown):\n\n"
    block += "![Remote host utilization](figs/host_utilization.png)\n\n"
    block += "Current recovery state: "+state["next"]+"\n\n"
    if state.get("cancelled_plans"):
        block += "User-cancelled obsolete retries (unlaunched; original plans retained):\n\n"
        block += markdown_table([{"id": "[" + exp_id + "](" + record["md_path"] + ")", **record}
                                 for exp_id, record in state["cancelled_plans"].items()],
                                ["id", "parent", "status", "time", "reason"])
        block += "\nNo measured result rows were created for these cancellations.\n\n"
    block += "<!-- AUTO: WORKSTREAM END -->\n"
    path = ROOT / "experiments/WEIGHT_LOADING.md"
    text = path.read_text()
    start, end = "<!-- AUTO: WORKSTREAM START -->", "<!-- AUTO: WORKSTREAM END -->"
    if start in text:
        before, after = text.split(start, 1)
        text = before+block+after.split(end, 1)[1]
    else:
        text += "\n"+block
    path.write_text(text)
    path = ROOT / "docs/0004-t8-weight-loading-plan.md"
    text = path.read_text()
    doc_rows = [{**row, "id": "["+row["id"]+"](../experiments/"+row["md_path"]+")"} for row in rows]
    table = start+"\n\n已归档数字（脚本生成；HLS 与 RTL/布线分列）：\n\n"
    table += markdown_table(doc_rows, hls_columns)
    table += "\n"+markdown_table([row for row in doc_rows if row["operation"] in {"cosim", "impl"}], physical_columns)
    table += "\n负 WNS 对应的周期只作估计，不能当作时序通过；缺失值为 unknown。\n\n"+end+"\n\n"
    if start in text:
        before, after = text.split(start, 1)
        text = before+table+after.split(end, 1)[1].lstrip("\n")
    else:
        text = text.replace("### 第 6 节暂定决策", table+"### 第 6 节暂定决策", 1)
    path.write_text(text)
    print("Summarized workstream:", ", ".join(row["id"] for row in rows))


if __name__ == "__main__":
    main()
